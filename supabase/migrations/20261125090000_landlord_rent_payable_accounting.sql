-- Records the landlord payout in the books when it is sent (accounting only: platform legs, no wallet leg, nothing about
-- the payout itself changes). "Sent" uses the statuses the system already treats as the landlord being paid
-- (start_repaying_on_landlord_paid): awaiting_agent_receipt, disbursed, completed.
--   sent             : DR L4 landlord_rent_payout_settled (cash_in) / CR A1 landlord_rent_payout_cash (cash_out)
--   failed after sent: the same legs with directions swapped (groups balance on direction, as every ledger group does)
-- A posting failure never blocks the payout: it is written to landlord_rent_payout_posting_exceptions instead.
CREATE TABLE public.landlord_rent_payout_posting_exceptions (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  payout_id   uuid NOT NULL,
  status      text,
  amount      numeric,
  error       text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  resolved_at timestamptz
);
