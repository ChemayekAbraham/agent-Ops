CREATE OR REPLACE FUNCTION public.post_landlord_rent_payout_accounting()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_sent  constant text[] := ARRAY['awaiting_agent_receipt', 'disbursed', 'completed'];
  v_net   numeric;
  v_n     int;
  v_dir   text;   -- direction of the L4 leg; the A1 leg takes the opposite
  v_td    timestamptz;
  v_ref   text;
  v_what  text;
BEGIN
  IF NEW.rent_request_id IS NULL OR COALESCE(NEW.amount, 0) <= 0 THEN
    RETURN NEW;
  END IF;
  IF NEW.status = ANY (v_sent) AND (TG_OP = 'INSERT' OR NOT (OLD.status = ANY (v_sent))) THEN
    v_dir := 'cash_in';   v_what := 'sent';
  ELSIF NEW.status = 'failed' AND TG_OP = 'UPDATE' AND OLD.status = ANY (v_sent) THEN
    v_dir := 'cash_out';  v_what := 'failed after being sent';
  ELSE
    RETURN NEW;
  END IF;

  BEGIN
    -- net already recorded for this payout (sent minus reversed)
    SELECT COALESCE(SUM(CASE WHEN g.direction = 'cash_in' THEN g.amount ELSE -g.amount END), 0), count(*)
      INTO v_net, v_n
      FROM public.general_ledger g
     WHERE g.source_table = 'landlord_payouts' AND g.source_id = NEW.id AND g.category = 'landlord_rent_payout_settled';
    IF (v_dir = 'cash_in' AND v_net > 0) OR (v_dir = 'cash_out' AND v_net <= 0) THEN
      RETURN NEW;  -- already recorded / nothing to reverse
    END IF;

    v_td  := CASE WHEN v_dir = 'cash_in' THEN COALESCE(NEW.finops_disbursed_at, NEW.disbursed_at, now()) ELSE now() END;
    v_ref := COALESCE(NULLIF(NEW.finops_momo_reference, ''), NULLIF(NEW.external_reference, ''), NEW.id::text);
    PERFORM public.create_ledger_transaction(jsonb_build_array(
      jsonb_build_object('ledger_scope', 'platform', 'direction', v_dir, 'amount', NEW.amount, 'category', 'landlord_rent_payout_settled',
        'source_table', 'landlord_payouts', 'source_id', NEW.id, 'reference_id', v_ref, 'currency', 'UGX', 'transaction_date', v_td,
        'description', format('Landlord rent payout %s to %s (UGX %s, ref %s): rent owed to the landlord for Rent Plan %s',
                              v_what, COALESCE(NEW.landlord_name, 'landlord'), NEW.amount, v_ref, left(NEW.rent_request_id::text, 8))),
      jsonb_build_object('ledger_scope', 'platform', 'direction', CASE WHEN v_dir = 'cash_in' THEN 'cash_out' ELSE 'cash_in' END,
        'amount', NEW.amount, 'category', 'landlord_rent_payout_cash',
        'source_table', 'landlord_payouts', 'source_id', NEW.id, 'reference_id', v_ref, 'currency', 'UGX', 'transaction_date', v_td,
        'description', format('Landlord rent payout %s (UGX %s, ref %s): cash paid to the landlord', v_what, NEW.amount, v_ref))),
      'landlord_rent_payout:' || NEW.id::text || ':' || (v_n + 1)::text, false);
  EXCEPTION WHEN OTHERS THEN
    INSERT INTO public.landlord_rent_payout_posting_exceptions (payout_id, status, amount, error)
    VALUES (NEW.id, NEW.status, NEW.amount, SQLERRM);
  END;
  RETURN NEW;
END $function$;

REVOKE ALL ON FUNCTION public.post_landlord_rent_payout_accounting() FROM PUBLIC, anon, authenticated;

CREATE TRIGGER trg_zz_post_landlord_rent_payout_accounting
  AFTER INSERT OR UPDATE OF status ON public.landlord_payouts
  FOR EACH ROW EXECUTE FUNCTION public.post_landlord_rent_payout_accounting();
