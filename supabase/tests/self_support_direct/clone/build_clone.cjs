// Builds stmts.sql (production public schema, structure only) from the JSON exports.
const fs = require('fs'), path = require('path');
const D = __dirname;
const rd = f => { const t = fs.readFileSync(path.join(D, f), 'utf8'); return JSON.parse(t.slice(t.indexOf('{'))).rows; };
const q = s => '"' + s.replace(/"/g, '""') + '"';
const TAG = '$CLONEX9$';
const stmts = [];
const add = (phase, sql) => { if (sql.includes(TAG)) throw new Error('tag clash'); stmts.push([phase, sql]); };
for (const t of rd('types.json')) {
  if (t.k === 'e') add(1, `CREATE TYPE public.${q(t.n)} AS ENUM (${JSON.parse(t.d).map(l => "'" + l.replace(/'/g, "''") + "'").join(', ')})`);
  else if (t.k === 'd') add(1, `CREATE DOMAIN public.${q(t.n)} AS ${t.d}`);
  else if (t.k === 's') add(1, t.d);
  else if (t.k === 'c') add(3, `CREATE TYPE public.${q(t.n)} AS (${t.d})`);
}
const defaults = [], cons = [], idx = [];
for (const t of rd('tables.json')) {
  const cols = (t.cols || []).map(c => {
    const ty = c.ty.replace(/extensions\.geography\([^)]*\)/, 'extensions.geography');
    let s = `${q(c.n)} ${ty}`;
    if (c.id === 'a') s += ' GENERATED ALWAYS AS IDENTITY';
    else if (c.id === 'd') s += ' GENERATED BY DEFAULT AS IDENTITY';
    if (c.nn) s += ' NOT NULL';
    if (c.g === 's') defaults.push(`ALTER TABLE public.${q(t.t)} DROP COLUMN ${q(c.n)}, ADD COLUMN ${q(c.n)} ${c.ty} GENERATED ALWAYS AS (${c.d}) STORED`);
    else if (c.d != null && !c.id) defaults.push(`ALTER TABLE public.${q(t.t)} ALTER COLUMN ${q(c.n)} SET DEFAULT ${c.d}`);
    return s;
  });
  add(2, `CREATE TABLE public.${q(t.t)} (${cols.join(', ')})`);
  for (const c of t.cons || []) cons.push(`ALTER TABLE public.${q(t.t)} ADD CONSTRAINT ${q(c.n)} ${c.d}`);
  for (const i of t.idx || []) idx.push(i);
}
for (const f of rd('funcs.json')) add(4, f.d);
for (const d of defaults) add(5, d);
for (const c of cons) add(6, c);
for (const i of idx) add(7, i);
for (const v of rd('views.json')) {
  if (v.k === 'v') add(8, `CREATE VIEW public.${q(v.n)}${v.opts ? ` WITH (${v.opts})` : ''} AS ${v.d}`);
  else add(8, `CREATE MATERIALIZED VIEW public.${q(v.n)} AS ${v.d.replace(/;\s*$/, '')} WITH NO DATA`);
}
for (const t of rd('trigs.json')) { add(9, t.d); if (t.dis) add(10, t.dis); }
let out = '';
stmts.forEach(([p, s], i) => { out += `INSERT INTO public._clone_stmts (seq, phase, sql) VALUES (${i + 1}, ${p}, ${TAG}${s}${TAG});\n`; });
fs.writeFileSync(path.join(D, 'stmts.sql'), out);
console.log('statements', stmts.length, 'bytes', out.length);
