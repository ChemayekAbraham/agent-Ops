import React, { useState } from 'react';
import { FileSpreadsheet, FileText, Loader2 } from 'lucide-react';
import {
  exportZoeReportPdf,
  exportZoeReportXlsx,
  type ZoeExportableReport,
} from '@/lib/zoe';

export interface ZoeReportCardProps {
  report: ZoeExportableReport;
}

/**
 * Report card rendered inside a Zoe assistant message bubble whenever the answer
 * is a table or a period summary. Displays:
 *   - Report title
 *   - Dates (`periodLabel`)
 *   - Row count (`rowCount`)
 *   - Generated time (`generatedAt`) and who generated it (`generatedBy`)
 *   - "How this was counted" note (`howCountedNote`)
 *   - PDF and Excel export buttons (minimum 44px tap targets, mobile-first)
 */
export const ZoeReportCard: React.FC<ZoeReportCardProps> = ({ report }) => {
  const [exportingPdf, setExportingPdf] = useState(false);
  const [exportingXlsx, setExportingXlsx] = useState(false);

  const handleExportPdf = async () => {
    if (exportingPdf) return;
    setExportingPdf(true);
    try {
      await exportZoeReportPdf(report);
    } finally {
      setExportingPdf(false);
    }
  };

  const handleExportXlsx = async () => {
    if (exportingXlsx) return;
    setExportingXlsx(true);
    try {
      await exportZoeReportXlsx(report);
    } finally {
      setExportingXlsx(false);
    }
  };

  const rowCountLabel = `${report.rowCount.toLocaleString('en-UG')} ${
    report.rowCount === 1 ? 'row' : 'rows'
  }`;

  return (
    <div
      data-testid="zoe-report-card"
      className="mt-3 rounded-lg border border-border bg-card p-3 text-card-foreground shadow-sm"
    >
      <div className="flex flex-col gap-1.5 sm:flex-row sm:items-start sm:justify-between">
        <div className="min-w-0 flex-1">
          <div className="flex flex-wrap items-center gap-1.5">
            <span className="inline-flex items-center rounded-md bg-primary/10 px-2 py-0.5 text-xs font-semibold text-primary">
              {report.kind === 'period_summary' ? 'Period Summary' : 'Report Table'}
            </span>
            <span
              data-testid="zoe-report-row-count"
              className="inline-flex items-center rounded-md border border-border bg-muted/60 px-2 py-0.5 text-xs font-medium text-foreground"
            >
              {rowCountLabel}
            </span>
          </div>
          <h3
            data-testid="zoe-report-title"
            className="mt-1.5 text-xs font-semibold leading-snug text-foreground sm:text-sm"
          >
            {report.title}
          </h3>
        </div>
      </div>

      <dl className="mt-2 grid grid-cols-1 gap-1.5 rounded-md border border-border/70 bg-muted/30 p-2 text-xs sm:grid-cols-3">
        <div>
          <dt className="font-medium text-muted-foreground">Dates</dt>
          <dd data-testid="zoe-report-dates" className="font-semibold text-foreground">
            {report.periodLabel}
          </dd>
        </div>
        <div>
          <dt className="font-medium text-muted-foreground">Generated time</dt>
          <dd data-testid="zoe-report-generated-at" className="font-semibold text-foreground">
            {report.generatedAt}
          </dd>
        </div>
        <div>
          <dt className="font-medium text-muted-foreground">Generated by</dt>
          <dd
            data-testid="zoe-report-generated-by"
            className="truncate font-semibold text-foreground"
            title={report.generatedBy}
          >
            {report.generatedBy}
          </dd>
        </div>
      </dl>

      <div
        data-testid="zoe-report-how-counted"
        className="mt-2 rounded-md border border-primary/20 bg-primary/5 px-2.5 py-2 text-xs leading-relaxed text-foreground"
      >
        <span className="font-semibold text-primary">How this was counted: </span>
        <span>{report.howCountedNote}</span>
      </div>

      <div className="mt-2.5 flex flex-wrap items-center gap-2">
        <button
          type="button"
          onClick={() => void handleExportPdf()}
          disabled={exportingPdf}
          data-testid="zoe-report-pdf-button"
          className="inline-flex min-h-[44px] flex-1 items-center justify-center gap-1.5 rounded-lg border border-primary/30 bg-primary px-3 py-2 text-xs font-semibold text-primary-foreground transition-colors hover:bg-primary/90 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring disabled:opacity-60 sm:flex-none"
        >
          {exportingPdf ? (
            <Loader2 className="h-4 w-4 animate-spin shrink-0" aria-hidden="true" />
          ) : (
            <FileText className="h-4 w-4 shrink-0" aria-hidden="true" />
          )}
          <span>PDF</span>
        </button>

        <button
          type="button"
          onClick={() => void handleExportXlsx()}
          disabled={exportingXlsx}
          data-testid="zoe-report-excel-button"
          className="inline-flex min-h-[44px] flex-1 items-center justify-center gap-1.5 rounded-lg border border-border bg-background px-3 py-2 text-xs font-semibold text-foreground transition-colors hover:bg-muted focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring disabled:opacity-60 sm:flex-none"
        >
          {exportingXlsx ? (
            <Loader2 className="h-4 w-4 animate-spin shrink-0" aria-hidden="true" />
          ) : (
            <FileSpreadsheet className="h-4 w-4 shrink-0" aria-hidden="true" />
          )}
          <span>Excel</span>
        </button>
      </div>
    </div>
  );
};

export default ZoeReportCard;
