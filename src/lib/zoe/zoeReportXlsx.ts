/**
 * Excel (.xlsx) Export Builder for Zoe (My Space Staff Assistant).
 *
 * Prompt 1 item (3) rules enforced here:
 *   - Every download filename ends in `.xlsx` (`ensureXlsxFilename`).
 *   - Numbers are written as numeric cells (`t="n"`) with `"UGX "#,##0` format for money
 *     and `yyyy-mm-dd` format for dates (`columnTypes` via `getZoeColumnXlsxType`).
 *   - Human column headers (`report.headers`), internal ID columns (`id`, `*_id`, UUIDs) hidden.
 *   - Frozen and auto-filtered header row (`freezeHeader: true`, `autoFilter: true`),
 *     sensible column widths, wrapped text, and a bold Totals row where applicable (`report.totalsRow`).
 *   - Final `"About this report"` sheet containing question, period, source, who asked,
 *     generated time, row count, and how this was counted.
 */
import {
  buildXlsxWorkbookBytes,
  ensureXlsxFilename,
  type XlsxSheetInput,
} from '@/lib/xlsxExport';
import {
  getZoeColumnXlsxType,
  type ZoeExportableReport,
} from './zoeReportData';

/**
 * Builds the `XlsxSheetInput[]` array for a `ZoeExportableReport`.
 *
 * - `sheets[0]` contains the exact `report.headers` and `report.rows` Zoe returned,
 *   typed with `columnTypes` (`money`, `integer`, `decimal`, `date`, `text`),
 *   frozen/auto-filtered header, and `totalsRow` when applicable.
 * - The final sheet (`About this report`) records the question, period, official source,
 *   who asked, generated time, row count, and how this was counted.
 */
export function buildZoeReportXlsxSheets(report: ZoeExportableReport): XlsxSheetInput[] {
  const dataSheets: XlsxSheetInput[] =
    report.sheets && report.sheets.length > 0
      ? report.sheets.map((s) => ({
          name: s.name,
          headers: [...s.headers],
          rows: s.rows.map((r) => [...r]),
          columnTypes: s.keys.map((k, idx) => getZoeColumnXlsxType(k, s.rows, idx)),
          freezeHeader: true,
          autoFilter: true,
          totalsRow: s.totalsRow ?? report.totalsRow,
        }))
      : [
          {
            name: 'Report Data',
            headers: [...report.headers],
            rows: report.rows.map((r) => [...r]),
            columnTypes: report.columns.map((k, idx) =>
              getZoeColumnXlsxType(k, report.rows, idx),
            ),
            freezeHeader: true,
            autoFilter: true,
            totalsRow: report.totalsRow,
          },
        ];

  const aboutSheet: XlsxSheetInput = {
    name: 'About this report',
    headers: ['Field', 'Value'],
    columnWidths: [26, 68],
    freezeHeader: true,
    autoFilter: false,
    rows: [
      ['Question', report.question],
      ['Report Title', report.title],
      ['Dates / Period', report.periodLabel],
      ['Official Source', report.source],
      ['Who Asked', report.generatedBy],
      ['Generated By', report.generatedBy],
      ['Generated Time', report.generatedAt],
      ['Row Count', report.rowCount],
      ['How This Was Counted', report.howCountedNote],
    ],
  };

  return [...dataSheets, aboutSheet];
}

/**
 * Builds the raw `.xlsx` ZIP/OpenXML bytes for a `ZoeExportableReport`.
 */
export async function buildZoeReportXlsxBytes(
  report: ZoeExportableReport,
): Promise<{ filename: string; bytes: Uint8Array; sheets: XlsxSheetInput[] }> {
  const filename = ensureXlsxFilename(`${report.filenameBase}.xlsx`);
  const sheets = buildZoeReportXlsxSheets(report);
  const bytes = await buildXlsxWorkbookBytes(sheets);
  return { filename, bytes, sheets };
}

/**
 * Generates and downloads an `.xlsx` workbook for the given Zoe report using `src/lib/xlsxExport.ts`.
 * Guarantees the download filename ends with `.xlsx`.
 */
export async function exportZoeReportXlsx(
  report: ZoeExportableReport,
): Promise<XlsxSheetInput[]> {
  const sheets = buildZoeReportXlsxSheets(report);
  const xlsxFilename = ensureXlsxFilename(`${report.filenameBase}.xlsx`);
  const { downloadXlsxWorkbook } = await import('@/lib/xlsxExport');
  await downloadXlsxWorkbook(xlsxFilename, sheets);
  return sheets;
}
