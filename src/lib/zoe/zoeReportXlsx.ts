/**
 * Excel (.xlsx) Export Builder for Zoe (My Space Staff Assistant).
 *
 * Uses `src/lib/xlsxExport.ts` (`downloadXlsxWorkbook`) and writes the exact
 * rows Zoe returned in the chat, alongside a "Report Info" sheet recording
 * the dates, generated time, who generated it, official source, row count,
 * and the "how this was counted" note.
 */
import type { XlsxSheet } from '@/lib/xlsxExport';
import type { ZoeExportableReport } from './zoeReportData';

/**
 * Builds the exact `XlsxSheet[]` array for a `ZoeExportableReport`.
 *
 * - `sheets[0]` contains the exact `report.headers` and `report.rows` Zoe returned.
 * - Additional data sheets (when a tool returned multiple named arrays) follow.
 * - The final sheet (`Report Info`) contains the report title, dates, generated time,
 *   who generated it, official source, row count, and the "how this was counted" note.
 */
export function buildZoeReportXlsxSheets(report: ZoeExportableReport): XlsxSheet[] {
  const dataSheets: XlsxSheet[] =
    report.sheets.length > 0
      ? report.sheets.map((s) => ({
          name: s.name,
          headers: [...s.headers],
          rows: s.rows.map((r) => [...r]),
        }))
      : [
          {
            name: 'Report Data',
            headers: [...report.headers],
            rows: report.rows.map((r) => [...r]),
          },
        ];

  const infoSheet: XlsxSheet = {
    name: 'Report Info',
    headers: ['Field', 'Value'],
    rows: [
      ['Report Title', report.title],
      ['Dates / Period', report.periodLabel],
      ['Generated Time', report.generatedAt],
      ['Generated By', report.generatedBy],
      ['Official Source', report.source],
      ['Row Count', report.rowCount],
      ['How This Was Counted', report.howCountedNote],
    ],
  };

  return [...dataSheets, infoSheet];
}

/**
 * Generates and downloads an `.xlsx` workbook for the given Zoe report using `src/lib/xlsxExport.ts`.
 */
export async function exportZoeReportXlsx(
  report: ZoeExportableReport,
): Promise<XlsxSheet[]> {
  const sheets = buildZoeReportXlsxSheets(report);
  const { downloadXlsxWorkbook } = await import('@/lib/xlsxExport');
  await downloadXlsxWorkbook(report.filenameBase, sheets);
  return sheets;
}
