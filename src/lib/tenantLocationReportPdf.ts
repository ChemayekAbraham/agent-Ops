/**
 * Tenant Location Report PDF (client-side, jspdf + jspdf-autotable).
 *
 * Built from the FULL tlb_tenants_multi result, never from a paginated page.
 * Read-only reporting: no wallet, ledger, Rent Plan or tenant record is touched.
 * The PDF carries personal phone numbers, so every page says so and the caller
 * writes an audit row (logTlbLocationPdfExport) before the file is delivered.
 */
import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { kampalaTodayYmd } from '@/lib/kampalaDays';
import {
  assertWithinExportCap,
  groupTenantsByPlace,
  STATUS_LABEL,
  type TlbPlaceReport,
} from '@/lib/tenantLocationSelection';
import type { TlbMultiTenant, TlbSelectedPlace, TlbStatus } from '@/hooks/useTenantLocationsBrowser';

type RGB = [number, number, number];
const BRAND: RGB = [108, 33, 196];
const BRAND_DARK: RGB = [76, 22, 150];
const INK: RGB = [30, 41, 59];
const MUTED: RGB = [100, 116, 139];
const ZEBRA: RGB = [247, 244, 252];
const LINE: RGB = [226, 232, 240];

export const TLB_PDF_CONFIDENTIAL = 'Confidential: contains personal phone numbers';

/** Latin-1 safe text: jsPDF's built-in fonts cannot draw other characters. */
export function pdfText(value: unknown): string {
  return String(value ?? '')
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/[–—]/g, '-')
    .replace(/…/g, '...')
    .replace(/[^ -~ -ÿ]/g, '')
    .trim();
}

const dash = (v: unknown) => pdfText(v) || '-';

/** "Rent Plan" wording applies: statuses are shown as plain words. */
export const statusWords = (status: string | null | undefined) =>
  status ? pdfText(status.replace(/_/g, ' ')) : '-';

/** 30 Oct 2026, 14:05 EAT, always in Kampala time whatever the device clock zone is. */
export function kampalaStamp(now: Date): string {
  const parts = new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Africa/Kampala', day: 'numeric', month: 'short', year: 'numeric',
    hour: '2-digit', minute: '2-digit', hour12: false,
  }).formatToParts(now);
  const get = (t: string) => parts.find((p) => p.type === t)?.value ?? '';
  return `${get('day')} ${get('month')} ${get('year')}, ${get('hour')}:${get('minute')} EAT`;
}

export function tenantLocationPdfFilename(places: readonly TlbSelectedPlace[], now: Date = new Date()): string {
  const first = (places[0]?.label ?? 'Places').normalize('NFKD').replace(/[^A-Za-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 30) || 'Places';
  const ymd = (Number.isNaN(now.getTime()) ? kampalaTodayYmd() : new Intl.DateTimeFormat('en-CA', { timeZone: 'Africa/Kampala' }).format(now));
  return `Welile_Tenants_${first}_${places.length}-places_${ymd}.pdf`;
}

export interface TenantLocationPdfInput {
  places: readonly TlbSelectedPlace[];
  rows: readonly TlbMultiTenant[];
  /** Distinct tenants matching on the server (rows.length unless the cap was hit). */
  total: number;
  status: TlbStatus;
  generatedBy: string;
  now?: Date;
}

export interface BuiltTenantLocationPdf {
  blob: Blob;
  filename: string;
  report: TlbPlaceReport;
  pages: number;
}

export function buildTenantLocationPdf(input: TenantLocationPdfInput): BuiltTenantLocationPdf {
  assertWithinExportCap(input.total);
  const now = input.now ?? new Date();
  const report = groupTenantsByPlace(input.places, input.rows);
  const doc = new jsPDF({ unit: 'mm', format: 'a4', orientation: 'portrait' });
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  const margin = 12;

  // Page 1 header: brand band, title, meta.
  doc.setFillColor(...BRAND);
  doc.rect(0, 0, pageW, 30, 'F');
  doc.setFillColor(239, 176, 46);
  doc.rect(0, 30, pageW, 1.2, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text('WELILE', margin, 11);
  doc.setFontSize(18);
  doc.text('Tenant Location Report', margin, 21);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.text(TLB_PDF_CONFIDENTIAL, pageW - margin, 11, { align: 'right' });

  doc.setTextColor(...INK);
  doc.setFontSize(9);
  const meta: [string, string][] = [
    ['Generated', kampalaStamp(now)],
    ['Generated by', dash(input.generatedBy)],
    ['Status filter', STATUS_LABEL[input.status]],
    ['Places selected', String(input.places.length)],
  ];
  let y = 38;
  for (const [k, v] of meta) {
    doc.setFont('helvetica', 'bold');
    doc.text(`${k}:`, margin, y);
    doc.setFont('helvetica', 'normal');
    doc.text(v, margin + 30, y);
    y += 5;
  }

  // Summary of the selected places, with grand totals.
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('Selected places', margin, y + 4);
  autoTable(doc, {
    startY: y + 7,
    margin: { left: margin, right: margin, bottom: 16 },
    head: [['Place', 'Full path', 'Total', 'Active', 'Inactive']],
    body: report.sections.map((s) => [
      dash(s.place.label), dash(s.place.fullPath.join(' > ')), String(s.total), String(s.active), String(s.inactive),
    ]),
    foot: [['Grand total', `${report.sections.length} places, each tenant counted once`, String(report.grand.total), String(report.grand.active), String(report.grand.inactive)]],
    showHead: 'everyPage',
    showFoot: 'lastPage',
    styles: { font: 'helvetica', fontSize: 8.5, cellPadding: 2, textColor: INK, lineColor: LINE, lineWidth: 0.1, overflow: 'linebreak' },
    headStyles: { fillColor: BRAND, textColor: 255, fontStyle: 'bold' },
    footStyles: { fillColor: BRAND_DARK, textColor: 255, fontStyle: 'bold' },
    alternateRowStyles: { fillColor: ZEBRA },
    columnStyles: {
      0: { cellWidth: 38, fontStyle: 'bold' },
      1: { cellWidth: 'auto' },
      2: { cellWidth: 16, halign: 'right' },
      3: { cellWidth: 16, halign: 'right' },
      4: { cellWidth: 18, halign: 'right' },
    },
  });

  // One section per place: heading, full path, tenants table.
  for (const section of report.sections) {
    doc.addPage();
    doc.setFillColor(...BRAND_DARK);
    doc.rect(margin, 14, pageW - margin * 2, 11, 'F');
    doc.setTextColor(255, 255, 255);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.text(dash(section.place.label), margin + 3, 20.5);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.text(`${section.total} tenants  |  ${section.active} active  |  ${section.inactive} inactive`, pageW - margin - 3, 20.5, { align: 'right' });
    doc.setTextColor(...MUTED);
    const pathLines = doc.splitTextToSize(dash(section.place.fullPath.join(' > ')), pageW - margin * 2);
    doc.text(pathLines, margin, 30);
    const tableY = 30 + pathLines.length * 4 + 2;

    autoTable(doc, {
      startY: tableY,
      margin: { left: margin, right: margin, top: 14, bottom: 16 },
      head: [['#', 'Name', 'Phone', 'Agent', 'Rent Plan status', 'Status']],
      body: section.rows.length
        ? section.rows.map((r, i) => [
            String(i + 1), dash(r.tenant_name), dash(r.tenant_phone), dash(r.agent_name),
            statusWords(r.latest_status), r.is_active ? 'Active' : 'Inactive',
          ])
        : [['', 'No tenants for this filter', '', '', '', '']],
      showHead: 'everyPage',
      styles: { font: 'helvetica', fontSize: 8, cellPadding: 1.8, textColor: INK, lineColor: LINE, lineWidth: 0.1, overflow: 'linebreak' },
      headStyles: { fillColor: BRAND, textColor: 255, fontStyle: 'bold' },
      alternateRowStyles: { fillColor: ZEBRA },
      columnStyles: {
        0: { cellWidth: 10, halign: 'right' },
        1: { cellWidth: 46 },
        2: { cellWidth: 30 },
        3: { cellWidth: 40 },
        4: { cellWidth: 'auto' },
        5: { cellWidth: 18 },
      },
    });
  }

  // Footer on every page: confidentiality line and "Page n of m".
  const pages = doc.getNumberOfPages();
  for (let p = 1; p <= pages; p++) {
    doc.setPage(p);
    doc.setDrawColor(...LINE);
    doc.line(margin, pageH - 11, pageW - margin, pageH - 11);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(...MUTED);
    doc.text(TLB_PDF_CONFIDENTIAL, margin, pageH - 6.5);
    doc.text(`Page ${p} of ${pages}`, pageW - margin, pageH - 6.5, { align: 'right' });
  }

  return {
    blob: doc.output('blob'),
    filename: tenantLocationPdfFilename(input.places, now),
    report,
    pages,
  };
}

// -- Delivery -----------------------------------------------------------------

/** Phones and tablets: the share sheet is the natural way to save or send a PDF. */
export function isTouchDevice(): boolean {
  if (typeof window === 'undefined') return false;
  try {
    return window.matchMedia?.('(pointer: coarse)').matches || (navigator.maxTouchPoints ?? 0) > 0;
  } catch {
    return false;
  }
}

export function canShareFile(file: File): boolean {
  try {
    return typeof navigator !== 'undefined' && typeof navigator.share === 'function'
      && typeof navigator.canShare === 'function' && navigator.canShare({ files: [file] });
  } catch {
    return false;
  }
}

function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 10_000);
}

/**
 * Hands the finished PDF to the person. Call it straight from a tap: on iOS the
 * share sheet only opens inside a fresh user gesture, so the PDF is generated
 * first and this runs on the next tap. Shares as a File where the device allows
 * it, otherwise downloads. Cancelling the share sheet is not an error.
 */
export async function deliverPdf(blob: Blob, filename: string): Promise<'shared' | 'downloaded' | 'cancelled'> {
  const file = new File([blob], filename, { type: 'application/pdf' });
  if (isTouchDevice() && canShareFile(file)) {
    try {
      await navigator.share({ files: [file], title: filename });
      return 'shared';
    } catch (err) {
      if ((err as { name?: string })?.name === 'AbortError') return 'cancelled';
      // Any other share failure: fall back to a normal download.
    }
  }
  downloadBlob(blob, filename);
  return 'downloaded';
}
